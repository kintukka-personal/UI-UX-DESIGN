#!/usr/bin/env python3
"""Write assets/js/search-index.js: what the header Search looks through.

    python3 tools/build_search_index.py      # needs beautifulsoup4

Reads the pages themselves, so run it again after editing a menu, an FAQ
answer, an experience or a page title/description.
"""
import json, os, re
from bs4 import BeautifulSoup

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
soup = lambda f: BeautifulSoup(open(os.path.join(ROOT, f), encoding='utf-8').read(), 'html.parser')
clean = lambda s: re.sub(r'\s+', ' ', s or '').strip()


def clip(s, n=150):
    s = clean(s)
    return s if len(s) <= n else s[:n].rsplit(' ', 1)[0] + '…'


# Pages, in the order they should win a tie. Extra words help short queries.
PAGES = [
    ('index.html', 'Home', 'private chef catering wollongong illawarra'),
    ('experiences.html', 'Our Experiences', 'prices packages compare'),
    ('menu.html', 'Menu', 'menus dishes food seasonal'),
    ('book.html', 'Book Now', 'enquire enquiry check your date availability booking'),
    ('weddings.html', 'Weddings', 'wedding reception rehearsal engagement'),
    ('corporate-events.html', 'Corporate events', 'work team building office christmas party client'),
    ('cooking-classes.html', 'Cooking classes', 'class lesson masterclass hens learn cook'),
    ('shop/egift-card.html', 'eGift Card', 'gift card voucher present birthday'),
    ('shop/degustation-voucher.html', '5-course Degustation voucher', 'gift voucher degustation'),
    ('shop/brooke-silks-signature-chilli-jam.html', 'Signature Chilli Jam', 'chilli jam shop buy'),
    ('shop.html', 'Shop', 'buy products'),
    ('faq.html', 'FAQ', 'questions answers help'),
    ('testimonials.html', 'Reviews & Press', 'reviews testimonials google press awards media'),
    ('contact.html', 'Contact Us', 'phone email hours contact question'),
    ('wollongong.html', 'Wollongong & the Illawarra', 'figtree local area'),
    ('south-coast.html', 'NSW South Coast', 'kiama gerringong berry holiday house rental'),
    ('southern-highlands.html', 'Southern Highlands', 'bowral mittagong highlands wedding'),
    ('sydney.html', 'Greater Sydney', 'sydney area'),
    ('cancellation-policy.html', 'Cancellations & Refunds', 'cancel refund reschedule policy'),
    ('terms-and-conditions.html', 'Terms & Conditions', 'terms travel fees deposit'),
    ('privacy-policy.html', 'Privacy Policy', 'privacy data'),
]

out = []
for f, name, extra in PAGES:
    s = soup(f)
    desc = (s.find('meta', attrs={'name': 'description'}) or {}).get('content', '')
    h1 = s.find('h1')
    out.append({'k': 'Page', 't': name, 'd': clip(desc), 'u': f, 'x': clean(extra + ' ' + (h1.get_text(' ') if h1 else ''))})

s = soup('experiences.html')
for card in s.select('article.exp-card'):
    title = card.find('h3').get_text(' ')
    price = card.select_one('p.price')
    tags = ' '.join(li.get_text(' ') for li in card.select('ul.tags li'))
    body = card.select('div.body > p')
    blurb = next((p.get_text(' ') for p in body if 'price' not in (p.get('class') or []) and 'minimum' not in (p.get('class') or [])), '')
    out.append({'k': 'Experience', 't': clean(title), 'd': clip(clean(price.get_text(' ')) + ' · ' + blurb if price else blurb),
                'u': 'experiences.html#' + card['id'], 'x': clean(tags)})

s = soup('menu.html')
for panel in s.select('div.menu-panel'):
    slug, menu = panel['data-slug'], clean(panel.find('h2').get_text(' '))
    for li in panel.select('li.menu-item'):
        desc = li.select_one('p.menu-item-desc')
        out.append({'k': 'Dish', 't': clean(li['data-name']), 'd': clip(menu + (' · ' + desc.get_text(' ') if desc else '')),
                    'u': 'menu.html#' + slug, 'x': ''})

s = soup('faq.html')
for li in s.select('.faq-group .accordion > li[id]'):
    q = clean(li.select_one('h3 button').get_text(' '))
    a = li.select_one('.answer')
    out.append({'k': 'FAQ', 't': q, 'd': clip(a.get_text(' ') if a else ''), 'u': 'faq.html#' + li['id'], 'x': ''})

js = ('/* What the header Search looks through. Generated by tools/build_search_index.py:\n'
      '   run it again after editing a menu, an FAQ answer, an experience or a page title. */\n'
      'window.DINE_IN_SEARCH = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')).replace('},{', '},\n{') + ';\n')
open(os.path.join(ROOT, 'assets/js/search-index.js'), 'w', encoding='utf-8').write(js)
kinds = {}
for e in out:
    kinds[e['k']] = kinds.get(e['k'], 0) + 1
print('search index:', kinds, '%d KB' % (len(js.encode()) // 1024))
